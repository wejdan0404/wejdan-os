import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { ensureGovernedMemorySchema, saveGovernedMemory, previewGovernedMemory, exportGovernedMemory, deleteGovernedMemoryForTask } from './memory-governance.mjs';

const db = new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON; CREATE TABLE tasks(task_id TEXT PRIMARY KEY,trace_id TEXT NOT NULL); INSERT INTO tasks VALUES(\'task_mem_a\',\'trace_mem_a\'),(\'task_mem_b\',\'trace_mem_b\');');
ensureGovernedMemorySchema(db);
const source = { roleId: 'PMO-01', provider: 'ollama-local', model: 'qwen3:8b', stage: 'specialist', evidenceRefs: ['fixture:mem-1'] };
const first = saveGovernedMemory(db, { taskId: 'task_mem_a', traceId: 'trace_mem_a', key: 'project.scope', content: 'Scope includes a local offline prototype.', source });
assert.equal(first.version, 1);
const unchanged = saveGovernedMemory(db, { taskId: 'task_mem_a', traceId: 'trace_mem_a', key: 'project.scope', content: 'Scope includes a local offline prototype.', source });
assert.equal(unchanged.unchanged, true);
assert.equal(unchanged.version, 1);
const conflicting = saveGovernedMemory(db, { taskId: 'task_mem_a', traceId: 'trace_mem_a', key: 'project.scope', content: 'Scope includes public deployment.', source: { ...source, stage: 'reviewer' } });
assert.equal(conflicting.version, 2);
assert.equal(conflicting.conflict_state, 'needs_review');
const recordsA = previewGovernedMemory(db, 'task_mem_a');
assert.equal(recordsA.length, 2);
assert.equal(recordsA.every(record => record.conflict_state === 'needs_review'), true);
assert.equal(recordsA[1].supersedes_record_id, recordsA[0].record_id);
assert.equal(recordsA[1].source.role_id, 'PMO-01');
assert.equal(previewGovernedMemory(db, 'task_mem_b').length, 0);
const exportA = exportGovernedMemory(db, 'task_mem_a');
assert.equal(exportA.retention, 'manual owner deletion; no automatic TTL');
assert.throws(() => deleteGovernedMemoryForTask(db, 'task_mem_a'), /EXPLICIT_OWNER_MEMORY_DELETE_REQUIRED/);
assert.throws(() => saveGovernedMemory(db, { taskId: 'task_missing', traceId: 'trace_mem_a', key: 'x', content: 'orphan', source }), /FOREIGN KEY/);
assert.throws(() => saveGovernedMemory(db, { taskId: 'task_mem_a', traceId: 'trace_mem_a', key: 'x', content: 'no provenance', source: null }), /MEMORY_PROVENANCE_REQUIRED/);
assert.throws(() => saveGovernedMemory(db, { taskId: 'task_mem_a', traceId: 'trace_mem_a', key: 'too.large', content: 'x'.repeat(24001), source }), /INVALID_MEMORY_CONTENT/);
const deleted = deleteGovernedMemoryForTask(db, 'task_mem_a', { explicitOwnerAction: true });
assert.equal(deleted.deleted_records, 2);
assert.equal(previewGovernedMemory(db, 'task_mem_a').length, 0);
assert.equal(previewGovernedMemory(db, 'task_mem_b').length, 0);
assert.equal(db.prepare('PRAGMA integrity_check').get().integrity_check, 'ok');
console.log(JSON.stringify({ result: 'PASS', mode: 'in-memory-synthetic-sqlite', checks: ['task and trace source provenance required', 'version history and supersedes link', 'conflicting text remains flagged for review without silent overwrite', 'task isolation', 'task export includes manual retention policy', 'delete requires explicit owner action and is task-scoped', 'orphan memory rejected by foreign key', '24k per-record boundary', 'SQLite integrity'], live_codex_calls: 0, paid_calls: 0, n8n_runs: 0 }));
db.close();
