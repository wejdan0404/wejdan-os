import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';

const require=createRequire(join(process.env.CODEX_NODE_MODULES,'__smoke_test__.cjs'));
const {chromium}=require('playwright');
const browser=await chromium.launch({headless:true,...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{})});
const page=await browser.newPage({viewport:{width:1365,height:1000},acceptDownloads:true});
page.setDefaultTimeout(4000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
page.on('dialog',dialog=>dialog.accept());
try{
  await page.goto('http://127.0.0.1:8765/command-center/',{waitUntil:'domcontentloaded',timeout:6000});
  await page.waitForFunction(()=>document.querySelectorAll('.role-card').length===85,{timeout:6000});
  await page.getByRole('heading',{name:'نظرة عامة'}).waitFor();
  if(await page.locator('.role-card').count()!==85)throw Error('Default role catalog count is not 85');
  if(await page.locator('#operations-body tr').count()<1)throw Error('Expected persisted local task row');
  if(await page.locator('#task-count').innerText()!==await page.locator('#metric-total').innerText())throw Error('Navigation task count differs from the persisted task metric');
  if((await page.locator('body').innerText()).includes('TRACE-SYN-1042'))throw Error('A stale sample inbox row is presented as live data');
  if(!(await page.locator('body').innerText()).includes('Ollama'))throw Error('Local model health is not displayed');
  await page.getByRole('button',{name:'Switch to English'}).click();
  if(await page.locator('html').getAttribute('dir')!=='ltr')throw Error('English direction did not switch to LTR');
  await page.getByRole('heading',{name:'Overview'}).waitFor();
  if(await page.locator('#task-search').getAttribute('placeholder')!=='Search tasks…')throw Error('English search placeholder did not localize');
  await page.locator('#role-search').fill('AI Observability');
  if(await page.locator('.role-card').count()!==1)throw Error('Role search did not narrow to one role');
  await page.locator('#role-search').fill('');
  await page.locator('#status-filter').selectOption('completed');
  if(await page.locator('#operations-body tr').count()<1)throw Error('Task status filter failed');
  await page.locator('#status-filter').selectOption('all');
  await page.getByRole('button',{name:/trace_/}).first().click();
  await page.getByRole('dialog').waitFor({state:'visible'});
  if(!(await page.getByRole('dialog').innerText()).includes('qwen3:8b'))throw Error('Trace dialog missing real local model result');
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({state:'hidden'});
  const before=await page.locator('#operations-body tr').count();
  await page.getByLabel('New task').fill('Provide two concise synthetic test checks. Do not perform external actions.');
  await page.getByLabel('Choose role').selectOption('D-00');
  await page.locator('#task-collaborate').check();
  await page.locator('#task-requires-approval').check();
  await page.getByRole('button',{name:'Run locally'}).click();
  await page.locator('#task-submit-status').getByText(/Waiting for human review:/).waitFor({timeout:240000});
  const submittedStatus=await page.locator('#task-submit-status').innerText();
  const submittedTaskId=submittedStatus.match(/task_[0-9a-f-]{36}/i)?.[0];
  if(!submittedTaskId)throw Error('Submission status omitted persisted task ID');
  if(await page.locator('#approval-list .approval-item').count()!==1)throw Error('Local approval request was not rendered from persisted API data');
  await page.getByRole('button',{name:'Record approval'}).click();
  await page.getByRole('button',{name:/trace_/}).first().click();
  const reviewedTaskDetails=await page.getByRole('dialog').innerText();
  if(!reviewedTaskDetails.includes('QA-01')||!reviewedTaskDetails.includes('Reviewer verdict')||!reviewedTaskDetails.includes('Approved'))throw Error('Approved task trace is missing reviewer or decision evidence');
  await page.keyboard.press('Escape');
  if(!(await page.locator('#operations-body').innerText()).includes(submittedTaskId))throw Error('Submitted task was not persisted and rendered');
  await page.getByRole('button',{name:/trace_/}).first().click();
  const collaborationDetails=await page.getByRole('dialog').innerText();
  if(!collaborationDetails.includes('QA-01')||!collaborationDetails.includes('reviewer')||!collaborationDetails.includes('n8n #'))throw Error('Trace dialog is missing persisted producer/reviewer evidence');
  await page.keyboard.press('Escape');
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Export redacted summary'}).click();
  const download=await downloadPromise;const downloadPath=await download.path();const report=JSON.parse(await readFile(downloadPath,'utf8'));
  if(report.tasks.length<2||report.provider!=='mixed-local'||!report.tasks[0].trace_id)throw Error('Redacted export contents failed');
  await page.setViewportSize({width:375,height:812});
  const overflow=await page.locator('body').evaluate(el=>({scroll:el.scrollWidth,width:innerWidth,items:Array.from(document.querySelectorAll('*')).filter(x=>x.getBoundingClientRect().right>innerWidth+2).slice(0,8).map(x=>({tag:x.tagName,id:x.id,cls:x.className,right:x.getBoundingClientRect().right}))}));
  if(overflow.scroll>overflow.width+2)throw Error(`Narrow layout overflows horizontally: ${JSON.stringify(overflow)}`);
  await page.getByRole('button',{name:'التبديل إلى العربية'}).click();
  if(await page.locator('html').getAttribute('dir')!=='rtl')throw Error('Arabic direction did not switch to RTL');
  if(await page.locator('#task-search').getAttribute('placeholder')!=='ابحثي عن مهمة…')throw Error('Arabic search placeholder did not localize');
  if(errors.length)throw Error(`Browser errors: ${errors.join('; ')}`);
  await page.setViewportSize({width:1365,height:1000});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'ops/evidence/local-command-center-live.png'});
  console.log('PASS: 85 canonical role profiles, persisted SQLite tasks, local n8n/Ollama health, bilingual direction, role/task filters, real task submission via UI, trace details, redacted export, 375px responsive width, zero page errors.');
}finally{await browser.close()}
